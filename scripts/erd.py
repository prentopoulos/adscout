"""Generate the entity-relationship diagram from a freshly migrated database.

    uv run --locked python scripts/erd.py

Writes `docs/architecture/erd.md` as a Mermaid `erDiagram`; a test fails when the committed
file differs from a fresh generation, so the diagram cannot drift from the schema.
"""

import sqlite3
import sys
import tempfile
from pathlib import Path

from adscout.db.migrate import upgrade

ROOT = Path(__file__).resolve().parent.parent
ERD = ROOT / "docs" / "architecture" / "erd.md"


def mermaid(connection: sqlite3.Connection) -> str:
    tables = [
        row[0]
        for row in connection.execute(
            "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%' "
            "ORDER BY name"
        )
    ]
    blocks, links = [], []
    for table in tables:
        keys_by_id: dict[int, tuple[str, list[str]]] = {}
        for row in connection.execute(f"PRAGMA foreign_key_list({table})").fetchall():
            keys_by_id.setdefault(row[0], (row[2], []))[1].append(row[3])
        foreign = {column for _, columns in keys_by_id.values() for column in columns}
        lines = [f"    {table} {{"]
        for column in connection.execute(f"PRAGMA table_info({table})").fetchall():
            name, kind, primary = column[1], column[2] or "ANY", column[5]
            keys = ["PK"] if primary else []
            if name in foreign:
                keys.append("FK")
            lines.append(f"        {kind} {name}{' ' + ', '.join(keys) if keys else ''}")
        lines.append("    }")
        blocks.append("\n".join(lines))
        for parent, columns in keys_by_id.values():
            links.append(f'    {table} }}o--|| {parent} : "{", ".join(columns)}"')
    return "erDiagram\n" + "\n".join(blocks) + "\n" + "\n".join(sorted(set(links))) + "\n"


def document() -> str:
    with tempfile.TemporaryDirectory() as folder:
        path = Path(folder) / "erd.db"
        upgrade(path)
        connection = sqlite3.connect(path)
        try:
            diagram = mermaid(connection)
        finally:
            connection.close()
    return (
        "# AdScout database (entity-relationship diagram)\n\n"
        "Generated by `scripts/erd.py` from a freshly migrated database; do not edit by hand.\n"
        "Every table is STRICT. `leads` refuses updates and deletes of its source fields, and\n"
        "`fake_crm_*` tables are the local stand-in for the CRM sandbox until Phase 4.\n\n"
        "```mermaid\n" + diagram + "```\n"
    )


def main(argv: list[str]) -> int:
    if argv:
        print("usage: python scripts/erd.py")
        return 2
    ERD.write_text(document(), encoding="utf-8", newline="\n")
    print(f"wrote {ERD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
